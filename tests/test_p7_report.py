"""Report builder on synthetic result fixtures: one command regenerates every table and figure."""

import json

import pytest

from ahg import report
from ahg.timing import InvalidMeasurement
from p7_helpers import record, run


def _move(root, split, regime, recs, tie):
    d = root / split / f"{regime}-{tie}"
    d.mkdir(parents=True)
    import gzip
    (d / "raw.json.gz").write_bytes(gzip.compress(json.dumps(
        {"split": split, "regime": regime, "tie_break": tie, "records": recs}).encode()))
    return d


def fixture(tmp_path, g=10, with_uniform=True):
    root = tmp_path / "eval"
    recs = [record(i, n=12 if i < 30 else 20, g=g) for i in range(60)]
    recs += [record(100, solvable=False), record(101, certified=False)]
    for s in ("d28_val", "d28_test_id", "d28_test_size30"):
        _move(root, s, "ac", recs, "fifo")
    if with_uniform:
        _move(root, "d28_test_id", "uniform", recs, "fifo")
    return root


def test_split_table_has_every_method_and_quantity():
    raw = {"records": [record(i) for i in range(6)] + [record(9, solvable=False)]}
    rows = {r["method"]: r for r in report.split_table(raw)}
    assert set(rows) >= {"h0", "hmax", "hadd", "hff", "lmcut", "hsp", "gnn@0", "gnn@2", "mlp@1", "wl@0"}
    r = rows["lmcut"]
    assert (r["solvable"], r["solved"], r["coverage"], r["geo_expansions"]) == (6, 6, 1.0, pytest.approx(20))
    assert r["cost_ratio"] == pytest.approx(1.0) and r["python_ms"] == pytest.approx(0.002)
    assert r["fd_ms"] == pytest.approx(0.006) and r["peak_mem_mb"] == pytest.approx(1.0)
    assert r["overestimation_rate"] == pytest.approx(0.1)


def test_certification_coverage_and_unsolvable_reasons_are_reported():
    raw = {"records": [record(0), record(1, certified=False), record(2, solvable=False)]}
    c = report.certification(raw)
    assert (c["tasks"], c["solvable"], c["unsolvable"], c["certified"]) == (3, 2, 1, 1)
    assert c["certification_coverage"] == 0.5 and c["unsolvable_reasons"] == {"no_foothold_on_goal_host_reachable": 1}


def test_cost_ratio_uses_certified_tasks_only():
    r0 = record(0, certified=False)
    rows = {r["method"]: r for r in report.split_table({"records": [r0]})}
    assert rows["lmcut"]["cost_ratio"] is None and rows["lmcut"]["cost_ratio_tasks"] == 0


def test_base_is_the_lowest_validation_geomean_with_ties_to_lmcut():
    recs = [record(i) for i in range(5)]
    assert report.pick_base(recs) == "lmcut"  # base=20 is the lowest of hmax 25, hadd 29, hff 27, hsp 23
    for r in recs:
        r["runs"]["hmax"]["expanded"] = 20
    assert report.pick_base(recs) == "lmcut"  # tie with h_max goes to LM-cut
    for r in recs:
        r["runs"]["hmax"]["expanded"] = 5
    assert report.pick_base(recs) == "hmax"
    with pytest.raises(InvalidMeasurement):
        report.pick_base([record(0, solvable=False)])


def test_comparison_excludes_trivial_and_unsolved_tasks_and_pairs_per_seed():
    recs = [record(i) for i in range(6)]
    recs[0]["hstar"] = 0  # trivial: counted, left out
    recs[1]["runs"]["gnn@1"]["cost"] = None  # unsolved by one GNN seed: task dropped from the comparison
    raw = {"records": recs}
    c = report.comparison(raw, "lmcut")
    assert (c["common"], c["trivial"]) == (4, 1) and len(c["task_values"]) == 4
    assert c["coverage_gnn"] == pytest.approx(5 / 6) and c["coverage_other"] == 1.0
    assert len(c["logs"]) == 2 and all(len(seeds) == 3 for seeds in c["logs"])  # 2 networks x 3 seeds
    assert report.comparison({"records": [record(0, solvable=False)]}, "lmcut") is None


def test_comparison_task_value_is_mean_seed_log_difference():
    import math
    c = report.comparison({"records": [record(0), record(1)]}, "lmcut")
    want = (math.log(10) + math.log(11) + math.log(12)) / 3 - math.log(20)
    assert c["task_values"] == [pytest.approx(want)] * 2


def test_full_report_regenerates_tables_figures_and_verdicts(tmp_path):
    root = fixture(tmp_path)
    path = report.build_report(root, tmp_path / "out", primary={"d28_test_id", "d28_test_size30"}, val_split="d28_val",
                               n_boot=200)
    text = path.read_text()
    for needle in ("Regime `ac` (primary)", "Regime `uniform` (secondary comparison, no verdict)", "h0", "hff", "lmcut",
                   "certification coverage", "Strongest classical baseline on `d28_val`: `lmcut`",
                   "Family size 6", "d28_test_id|GNN vs BASE", "d28_test_size30|GNN vs wl", "SUPPORTED"):
        assert needle in text, needle
    assert (tmp_path / "out" / "sizes_all.png").stat().st_size > 0 and (tmp_path / "out" / "tables.json").exists()
    again = report.build_report(root, tmp_path / "out2", primary={"d28_test_id", "d28_test_size30"}, val_split="d28_val",
                                n_boot=200)
    assert again.read_text() == text  # regenerated byte for byte (fixed bootstrap keys)


def test_uniform_runs_never_enter_the_verdict_family(tmp_path):
    root = fixture(tmp_path)
    text = report.build_report(root, tmp_path / "o", primary={"d28_test_id", "d28_test_size30"}, val_split="d28_val",
                               n_boot=200).read_text()
    verdict = text.split("## Verdict rule")[1]
    assert verdict.count("GNN vs BASE") == 2  # two primary splits, ac only


def test_slower_gnn_is_not_supported(tmp_path):
    root = fixture(tmp_path, g=40)  # GNN expands twice as many nodes as LM-cut
    text = report.build_report(root, tmp_path / "o", primary={"d28_test_id"}, val_split="d28_val", n_boot=200).read_text()
    assert "SUPPORTED" not in text.split("## Verdict rule")[1] and "REFUTED" in text


def test_missing_validation_or_primary_run_omits_verdicts_and_says_so(tmp_path):
    root = fixture(tmp_path)
    text = report.build_report(root, tmp_path / "o", primary={"nope"}, val_split="d28_val", n_boot=50).read_text()
    assert "Not built" in text


def test_empty_root_and_duplicate_runs_are_errors(tmp_path):
    with pytest.raises(FileNotFoundError):
        report.build_report(tmp_path / "none", tmp_path / "o", primary=set())
    root = fixture(tmp_path)
    d = root / "d28_test_id" / "ac-fifo-2"
    d.mkdir()
    import shutil
    shutil.copy(root / "d28_test_id" / "ac-fifo" / "raw.json.gz", d / "raw.json.gz")
    with pytest.raises(ValueError, match="two runs"):
        report.build_report(root, tmp_path / "o", primary=set())


def test_nonpositive_expansions_raise_not_clamp():
    recs = [record(0), record(1)]
    recs[0]["runs"]["gnn@0"]["expanded"] = 0
    with pytest.raises(InvalidMeasurement):
        report.comparison({"records": recs}, "lmcut")


def test_size_curves_group_by_model_and_size():
    recs = [record(0, n=12), record(1, n=20, g=30)]
    cur = report.size_curves({"s": {"records": recs}})
    assert set(cur["gnn"]) == {12, 20} and cur["gnn"][20] > cur["gnn"][12] and "lmcut" in cur
